import { motion } from "framer-motion";
import { useId, type ReactNode } from "react";

export const spring = { type: "spring", stiffness: 520, damping: 42, mass: 0.9 } as const;

export function SegmentedControl<T extends string | number>({
  options,
  value,
  onChange,
  label,
  size = "md",
}: {
  options: { value: T; label: ReactNode; title?: string }[];
  value: T;
  onChange: (v: T) => void;
  label: string;
  size?: "sm" | "md";
}) {
  const id = useId();
  return (
    <div className={`segmented segmented--${size}`} role="radiogroup" aria-label={label}>
      {options.map((o) => {
        const active = o.value === value;
        return (
          <button
            key={String(o.value)}
            type="button"
            role="radio"
            aria-checked={active}
            title={o.title}
            className={`segmented__item${active ? " is-active" : ""}`}
            onClick={() => onChange(o.value)}
          >
            {active && <motion.span layoutId={`seg-${id}`} className="segmented__thumb" transition={spring} />}
            <span className="segmented__label">{o.label}</span>
          </button>
        );
      })}
    </div>
  );
}

export function Toggle({
  checked,
  onChange,
  label,
  description,
}: {
  checked: boolean;
  onChange: (v: boolean) => void;
  label: string;
  description?: string;
}) {
  const id = useId();
  return (
    <label className="toggle" htmlFor={id}>
      <span className="toggle__text">
        <span className="toggle__label">{label}</span>
        {description && <span className="toggle__desc">{description}</span>}
      </span>
      <input id={id} type="checkbox" role="switch" checked={checked} onChange={(e) => onChange(e.target.checked)} />
      <span className="toggle__track" aria-hidden>
        <motion.span className="toggle__thumb" animate={{ x: checked ? 18 : 0 }} transition={spring} />
      </span>
    </label>
  );
}

